//! Quant Docs — Sheets engine (WebAssembly).
//!
//! A thin, typed adapter over the GridCraft engine: open an .xlsx (also .xls, .ods, .csv and
//! the other formats GridCraft reads) and return a bounded preview of every visible sheet —
//! the cells' displayed text (number formats, dates and computed formula results applied by
//! GridCraft), merges, and the real row numbers / column indexes so hidden rows and columns
//! stay hidden. Runs on the user's device, inside a Web Worker.
//!
//! Errors are `JsError`s whose message starts with a stable code (`E_INVALID`).

use gridcraft_core::CellRef;
use gridcraft_engine::{display, io};
use gridcraft_model::{Sheet, Workbook};
use serde_json::{Value, json};
use wasm_bindgen::prelude::*;

/// Hard caps so a huge sheet cannot exhaust the worker's memory.
const MAX_ROWS: u32 = 2_000;
const MAX_COLS: u32 = 200;

fn sheet_preview(wb: &Workbook, sh: &Sheet, max_rows: u32, max_cols: u32) -> Value {
    let Some(r) = sh.used_range() else {
        return json!({ "name": sh.name, "rows": [], "rowNumbers": [], "colIndexes": [], "merges": [],
                       "totalRows": 0, "totalCols": 0, "truncatedRows": false, "truncatedCols": false });
    };
    let rows: Vec<u32> = (r.start.row..=r.end.row).filter(|&row| !sh.is_row_hidden(row)).collect();
    let cols: Vec<u32> = (r.start.col..=r.end.col).filter(|&col| !sh.is_col_hidden(col)).collect();
    let shown_rows = &rows[..rows.len().min(max_rows as usize)];
    let shown_cols = &cols[..cols.len().min(max_cols as usize)];

    let mut out_rows = Vec::with_capacity(shown_rows.len());
    for &row in shown_rows {
        let mut cells = Vec::with_capacity(shown_cols.len());
        for &col in shown_cols {
            cells.push(Value::String(display::cell_text(wb, sh, CellRef::new(row, col))));
        }
        // Trailing empty cells carry nothing; the grid pads short rows.
        while matches!(cells.last(), Some(Value::String(s)) if s.is_empty()) {
            cells.pop();
        }
        out_rows.push(Value::Array(cells));
    }

    // Merges, re-expressed as indexes into the shown rows/columns.
    let pos = |list: &[u32], v: u32| list.iter().position(|&x| x == v);
    let merges: Vec<Value> = sh
        .merges
        .iter()
        .filter_map(|m| {
            let r0 = pos(shown_rows, m.start.row)?;
            let c0 = pos(shown_cols, m.start.col)?;
            let rs = shown_rows.iter().filter(|&&x| x >= m.start.row && x <= m.end.row).count();
            let cs = shown_cols.iter().filter(|&&x| x >= m.start.col && x <= m.end.col).count();
            (rs > 1 || cs > 1).then(|| json!([r0, c0, rs, cs]))
        })
        .collect();

    json!({
        "name": sh.name,
        "rows": out_rows,
        "rowNumbers": shown_rows.iter().map(|r| r + 1).collect::<Vec<_>>(),
        "colIndexes": shown_cols,
        "merges": merges,
        "totalRows": rows.len(),
        "totalCols": cols.len(),
        "truncatedRows": rows.len() > shown_rows.len(),
        "truncatedCols": cols.len() > shown_cols.len(),
    })
}

/// Preview every visible sheet of the workbook in `bytes` as JSON:
/// `{ sheets: [{ name, rows: string[][], rowNumbers, colIndexes, merges: [r, c, rowSpan, colSpan][],
///    totalRows, totalCols, truncatedRows, truncatedCols }], warnings: string[] }`.
#[wasm_bindgen(js_name = previewWorkbook)]
pub fn preview_workbook(name: &str, bytes: &[u8], max_rows: u32, max_cols: u32) -> Result<String, JsError> {
    let (mut wb, warnings) = io::open_bytes(name, bytes).map_err(|e| JsError::new(&format!("E_INVALID: {e}")))?;
    // Same as opening the workbook in GridCraft: compute every formula, so files saved without
    // cached results (generated by scripts, some exporters) still show their values.
    gridcraft_engine::calc::Calc::new().recalc_all(&mut wb);
    let max_rows = max_rows.clamp(1, MAX_ROWS);
    let max_cols = max_cols.clamp(1, MAX_COLS);
    let sheets: Vec<Value> = wb
        .sheets
        .iter()
        .filter(|sh| matches!(sh.visibility, gridcraft_model::Visibility::Visible))
        .map(|sh| sheet_preview(&wb, sh, max_rows, max_cols))
        .collect();
    if sheets.is_empty() {
        return Err(JsError::new("E_INVALID: the workbook has no visible sheets"));
    }
    Ok(json!({ "sheets": sheets, "warnings": warnings }).to_string())
}

#[wasm_bindgen(js_name = engineInfo)]
pub fn engine_info() -> String {
    format!("quant-sheets-engine {} (GridCraft, MIT OR Apache-2.0)", env!("CARGO_PKG_VERSION"))
}
