import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest';
import { UniversalSSOTokenBridge } from '@quant/shared-ui';
import { getAuthToken, setAuthToken, clearAuthSession } from '../lib/auth';
import {
  ingestSSOToken,
  getAccessToken,
  clearAccessToken,
  authSession,
} from '../services/auth-session';

describe('QuantAI SSO Token Handoff & Session Ingestion', () => {
  beforeEach(() => {
    localStorage.clear();
    clearAccessToken();
    clearAuthSession();
    vi.restoreAllMocks();
  });

  afterEach(() => {
    localStorage.clear();
    clearAccessToken();
    clearAuthSession();
  });

  it('reads auth token from quant_access_token and quant_auth_token in localStorage', () => {
    expect(getAuthToken()).toBeNull();

    localStorage.setItem('quant_access_token', 'jwt-quantai-access-111');
    expect(getAuthToken()).toBe('jwt-quantai-access-111');

    clearAuthSession();
    expect(getAuthToken()).toBeNull();

    localStorage.setItem('quant_auth_token', 'jwt-quantai-auth-222');
    expect(getAuthToken()).toBe('jwt-quantai-auth-222');
  });

  it('WR-SEC-001: setAuthToken keeps the access token in memory only (no JS-readable writes)', () => {
    const testToken = 'jwt-ai-token-333';
    setAuthToken(testToken, {
      id: 'usr_1',
      email: 'member@quantmail.in',
      name: 'Quant Member',
      plan: 'pro',
    });

    // Token must NOT land in JS-readable persistence (XSS exfiltration surface).
    expect(localStorage.getItem('quant_access_token')).toBeNull();
    expect(localStorage.getItem('quant_auth_token')).toBeNull();
    expect(localStorage.getItem('token')).toBeNull();
    expect(localStorage.getItem('quant_token')).toBeNull();
    expect(document.cookie).not.toContain(testToken);
    // Memory session still works for the tab lifetime.
    expect(getAuthToken()).toBe(testToken);
    // Non-secret profile still persists for the UI.
    expect(localStorage.getItem('quant_user')).toContain('member@quantmail.in');
  });

  it('ingestSSOToken keeps the SSO token in memory only (no JS-readable writes)', () => {
    const ssoToken = 'jwt-sso-ingested-444';
    ingestSSOToken(ssoToken);

    expect(getAccessToken()).toBe(ssoToken);
    expect(getAuthToken()).toBe(ssoToken);
    expect(localStorage.getItem('quant_access_token')).toBeNull();
    expect(document.cookie).not.toContain(ssoToken);
  });

  it('ingests __quant_sso_ticket generated by UniversalSSOTokenBridge for QuantAI', () => {
    const bridge = UniversalSSOTokenBridge.getInstance();

    bridge.setCurrentSession(
      {
        userId: 'user-ai-sso-2',
        email: 'ai-tester@quantmail.in',
        displayName: 'AI Tester',
        token: 'jwt-ai-sso-token-555',
        currentApp: 'quantai',
      },
      3600,
    );

    const ticket = bridge.generateHandoffTicket('quantai');
    expect(ticket).toBeTruthy();

    // Unwrap the ticket envelope (decode-only: verifies nothing by itself —
    // in production the wrapped token is re-verified server-side by
    // consumeHandoffTicket before any session is established)
    const unwrapped = bridge.decodeUnverifiedHandoffTicket(ticket!);
    expect(unwrapped).not.toBeNull();
    expect(unwrapped?.userId).toBe('user-ai-sso-2');
    expect(unwrapped?.token).toBe('jwt-ai-sso-token-555');

    // Ingest into quantai (memory-only under WR-SEC-001; the bridge-owned
    // localStorage keys are read back through getAuthToken until the SSO lane
    // migrates the bridge itself)
    ingestSSOToken(unwrapped!.token!);
    expect(getAccessToken()).toBe('jwt-ai-sso-token-555');
    expect(getAuthToken()).toBe('jwt-ai-sso-token-555');
  });

  it('authSession.refresh falls back to stored SSO token when /auth/refresh returns 401/network', async () => {
    localStorage.setItem('quant_access_token', 'jwt-cached-sso-666');

    // Stub global fetch with a rejection
    vi.stubGlobal('fetch', vi.fn().mockRejectedValue(new Error('Network error')));

    const result = await authSession.refresh();
    expect(result.success).toBe(true);
    expect(result.data?.accessToken).toBe('jwt-cached-sso-666');
    expect(getAccessToken()).toBe('jwt-cached-sso-666');
  });
});
