export function CommandIcon({
  name,
  className = 'w-4 h-4',
}: {
  name?: string;
  className?: string;
}) {
  const path = name ? PATHS[name] : undefined;
  if (!path) return null;

  return (
    <svg
      className={className}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.8"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      <path d={path} />
    </svg>
  );
}

/** Whether an icon name resolves to a glyph — lets callers reserve layout space. */
export function hasCommandIcon(name?: string): boolean {
  return Boolean(name && PATHS[name]);
}
